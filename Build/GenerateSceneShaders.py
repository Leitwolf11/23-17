"""Regenerate the embedded OpenGL and Vulkan shaders with glslc."""

from pathlib import Path
from subprocess import run
from tempfile import TemporaryDirectory

directory = Path(__file__).resolve().parent.parent / "Sources" / "Rendering"
open_gl = ["// Generated by Build/GenerateSceneShaders.py."]
vulkan = ["// Generated by Build/GenerateSceneShaders.py."]
with TemporaryDirectory() as temporary:
    for stage in ("vert", "frag"):
        raw = directory / f"Scene.{stage}"
        glsl = raw.read_text(encoding="utf-8")
        glsl = glsl.replace("#version 420 core", "#version 420 core\n#define OPENGL_SCENE 1")
        open_gl.append(f'constexpr const char *k{stage.title()}Source = R"glsl({glsl})glsl";')
        compiled = Path(temporary) / f"scene-{stage}.spv"
        run(["glslc", "--target-env=vulkan1.0", "-O", str(raw), "-o", str(compiled)], check=True)
        data = compiled.read_bytes()
        vulkan.append(f"alignas(4) constexpr unsigned char k{stage.title()}Spirv[] = {{")
        for start in range(0, len(data), 12):
            vulkan.append("    " + " ".join(f"0x{byte:02x}," for byte in data[start:start + 12]))
        vulkan.append("};")

(directory / "SceneOpenGl.inc").write_text("\n".join(open_gl) + "\n", encoding="utf-8")
(directory / "SceneSpirv.inc").write_text("\n".join(vulkan) + "\n", encoding="utf-8")
